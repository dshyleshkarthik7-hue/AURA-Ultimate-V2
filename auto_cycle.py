#!/usr/bin/env python3
"""Deprecated unsafe self-training workflow.

Teacher-generated pseudo-labels are not independent ground truth and must not be
used as both training labels and promotion-test labels. This command intentionally
refuses to collect pseudo-labels or promote a candidate model.

Use train.py only after collecting independently captured, human-labelled sessions.
Evaluate with evaluate.py on a session-held-out split, inspect per-class recall and
the confusion matrix, and promote a reviewed candidate explicitly.
"""
import argparse


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="config.yaml", help="Retained for CLI compatibility; no files are modified.")
    parser.add_argument("--seconds", type=int, default=45, help="Deprecated; no camera is opened.")
    parser.add_argument("--min-per-class", type=int, default=12, help="Deprecated; no pseudo-labels are collected.")
    parser.parse_args()
    raise SystemExit(
        "Automatic pseudo-label promotion is disabled: its evaluation labels were "
        "generated by the teacher and are not independent ground truth. Collect "
        "independent labelled capture sessions, then run train.py and evaluate.py."
    )


if __name__ == "__main__":
    main()
